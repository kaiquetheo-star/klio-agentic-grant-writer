#!/usr/bin/env python3
"""Generate golden traces for Open Agent Hackathon 2026 submission.

Runs three SAMPLE_MODE orchestrator executions, writes:
  - input_examples/reasoning_engine/example_N.json
  - output_examples/reasoning_engine/example_N_output.json
  - logs/golden_trace_example_N.jsonl
  - input_examples/reasoning_engine/README.md

Usage (from repo root or backend/):
  SAMPLE_MODE=true REASONING_ENGINE_ENABLED=true \\
    python backend/apps/reasoning_engine/scripts/generate_golden_trace.py
"""

from __future__ import annotations

import json
import os
import shutil
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[4]
BACKEND_DIR = REPO_ROOT / "backend"

os.environ["SAMPLE_MODE"] = "true"
os.environ["REASONING_ENGINE_ENABLED"] = "true"
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")
os.environ.setdefault("DJANGO_SECRET_KEY", "hackathon-golden-trace-dev-only")
os.environ.setdefault("DEBUG", "true")
os.environ.setdefault("DATABASE_URL", "sqlite:////tmp/klio-golden-trace.sqlite3")

if str(BACKEND_DIR) not in sys.path:
    sys.path.insert(0, str(BACKEND_DIR))

import django

django.setup()

from apps.reasoning_engine.services.orchestrator import ReasoningOrchestrator  # noqa: E402

EXAMPLES = [
    {
        "grant_id": "sample-grant-teatro-sp",
        "user_portfolio_text": (
            "Coletivo de teatro de rua com 5 anos de atuação, circulação em 12 cidades "
            "do interior de SP, oficinas comunitárias para jovens em situação de "
            "vulnerabilidade social, acessibilidade com audiodescrição e LIBRAS."
        ),
        "output_language": "pt-BR",
    },
    {
        "grant_id": "sample-grant-musica-rj",
        "user_portfolio_text": (
            "Independent chamber orchestra specialized in contemporary Brazilian repertoire, "
            "with 3 released albums, international tours, accessibility commitments and "
            "community workshops in Rio de Janeiro."
        ),
        "output_language": "en",
    },
    {
        "grant_id": "sample-grant-audiovisual-mg",
        "user_portfolio_text": (
            "Productora audiovisual enfocada en documentales sobre cultura afrobrasileña, "
            "con 2 cortometrajes premiados en festivales nacionales, accesibilidad "
            "(audiodescripción / lengua de señas) y circulación en Minas Gerais."
        ),
        "output_language": "es",
    },
]


def _write_examples_readme(summaries: list[dict]) -> None:
    lines = [
        "# Reasoning Engine — Sample Inputs (Hackathon Judges)",
        "",
        "Generated by `backend/apps/reasoning_engine/scripts/generate_golden_trace.py` "
        "with `SAMPLE_MODE=true` (no network, no secrets).",
        "",
        "| # | grant_id | language | status | score | revisions | golden trace |",
        "|---|----------|----------|--------|-------|-----------|--------------|",
    ]
    for s in summaries:
        lines.append(
            f"| {s['n']} | `{s['grant_id']}` | {s['language']} | {s['status']} | "
            f"{s['score']} | {s['revisions']} | `logs/golden_trace_example_{s['n']}.jsonl` |"
        )
    lines.extend(
        [
            "",
            "## How to regenerate",
            "",
            "```bash",
            "cd /opt/klio  # or your clone root",
            "export SAMPLE_MODE=true REASONING_ENGINE_ENABLED=true",
            "python backend/apps/reasoning_engine/scripts/generate_golden_trace.py",
            "```",
            "",
            "## Notes",
            "",
            "- Outputs are synthetic and labeled `[SAMPLE_MODE]`.",
            "- Matching `output_examples/reasoning_engine/example_N_output.json` holds the full API response.",
            "- Traces are JSONL with Planner → Writer → Evaluator handoffs and at least one revision.",
            "",
        ]
    )
    out = REPO_ROOT / "input_examples" / "reasoning_engine" / "README.md"
    out.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    input_dir = REPO_ROOT / "input_examples" / "reasoning_engine"
    output_dir = REPO_ROOT / "output_examples" / "reasoning_engine"
    logs_dir = REPO_ROOT / "logs"
    input_dir.mkdir(parents=True, exist_ok=True)
    output_dir.mkdir(parents=True, exist_ok=True)
    logs_dir.mkdir(parents=True, exist_ok=True)

    orchestrator = ReasoningOrchestrator()
    summaries: list[dict] = []

    for i, example in enumerate(EXAMPLES, 1):
        print(f"\n{'=' * 60}")
        print(f"Running example {i}: {example['grant_id']}")
        print(f"{'=' * 60}\n")

        result = orchestrator.run(
            grant_id=example["grant_id"],
            user_portfolio_text=example["user_portfolio_text"],
            output_language=example["output_language"],
        )

        input_file = input_dir / f"example_{i}.json"
        with input_file.open("w", encoding="utf-8") as fh:
            json.dump(example, fh, indent=2, ensure_ascii=False)
            fh.write("\n")

        output_file = output_dir / f"example_{i}_output.json"
        with output_file.open("w", encoding="utf-8") as fh:
            json.dump(result, fh, indent=2, ensure_ascii=False, default=str)
            fh.write("\n")

        trace_rel = result.get("log_file") or ""
        trace_file = REPO_ROOT / trace_rel
        golden_trace = logs_dir / f"golden_trace_example_{i}.jsonl"
        if trace_file.exists():
            shutil.copy(trace_file, golden_trace)
            print(f"✓ Trace saved: {golden_trace.relative_to(REPO_ROOT)}")
        else:
            print(f"✗ Trace missing: {trace_file}")

        status = result.get("status")
        score = (result.get("output") or {}).get("score")
        revisions = (result.get("output") or {}).get("revisions")
        print(f"✓ Status: {status}")
        print(f"✓ Score: {score}")
        print(f"✓ Revisions: {revisions}")
        print(f"✓ Input:  {input_file.relative_to(REPO_ROOT)}")
        print(f"✓ Output: {output_file.relative_to(REPO_ROOT)}")

        summaries.append(
            {
                "n": i,
                "grant_id": example["grant_id"],
                "language": example["output_language"],
                "status": status,
                "score": score,
                "revisions": revisions,
            }
        )

    _write_examples_readme(summaries)
    print(f"\n{'=' * 60}")
    print("Golden traces generated!")
    print(f"{'=' * 60}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
